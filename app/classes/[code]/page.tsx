import type { Metadata } from "next";
import Link from "next/link";
import { headers } from "next/headers";
import { notFound, redirect } from "next/navigation";
import { ArrowLeft, Monitor, Star, Zap } from "lucide-react";
import { Card, CardTitle, Layout } from "@/components/ui";
import { ClassEditor } from "@/components/ClassEditor";
import { AIBackgroundCard } from "@/components/AIContext";
import { TodayPanel } from "@/components/teacher/TodayPanel";
import { WeekPlanner } from "@/components/teacher/WeekPlanner";
import { Tabs } from "@/components/Tabs";
import { ArchiveToggle, CopyButton, FileToggle, LabelEditor, PlanSessionForm } from "@/components/teacher/TeacherControls";
import { getAccount, isTeacherAccount } from "@/lib/supabase-auth";
import { addDays, isDateKey, mondayOf, schoolDate, schoolWeekOf, weekdayOf } from "@/lib/time";
import type { ClassSession } from "@/lib/types";
import {
  classLabel, dayKey, dayLabel, loadClass, loadClasses, loadFiling, loadPresets, loadReviews, loadRoster, loadSessions, loadSessionsBetween,
  loadWorkouts, loadWorkoutsByIds, longDayLabel, timeLabel,
  type WorkoutRow,
} from "@/lib/teacher-data";
import { DEFAULT_CONFIG } from "@/lib/class-config";

export const dynamic = "force-dynamic";
export const metadata: Metadata = { title: "Class — PE.AI", robots: { index: false } };

type Params = Promise<{ code: string }>;
type Search = Promise<{ tab?: string; week?: string }>;

// The owner's page for one class: a teacher's class (tabs on iPad and computer:
// Sessions, Settings, AI background, Students, Workouts; one scroll on phones)
// or a student's personal class (settings + their history, one column).
export default async function OwnerClassPage({ params, searchParams }: { params: Params; searchParams: Search }) {
  const code = (await params).code.toUpperCase();
  const account = await getAccount();
  if (!account) redirect(`/login?next=/classes/${code}`);
  const home = isTeacherAccount(account) ? "/teacher" : "/me";

  // RLS also returns classes the caller merely joined; this page is owners only.
  const cls = await loadClass(code);
  if (!cls || cls.owner_id !== account.id) notFound();
  const personal = cls.kind === "personal";
  const today = schoolDate();
  const { tab, week } = await searchParams;
  // The week grid (docs/04 T4): this school week unless ?week= picks another.
  const thisWeek = schoolWeekOf(today);
  const weekStart = isDateKey(week) ? mondayOf(week) : thisWeek;
  const weekEnd = addDays(weekStart, 4);

  const [recent, reviews, filing, roster, sessions, presets, weekSessions, myClasses] = await Promise.all([
    loadWorkouts({ classCodes: [code], sinceDays: personal ? 90 : 14, limit: 300 }),
    personal ? Promise.resolve([]) : loadReviews([code], 14),
    loadFiling([cls]),
    personal ? Promise.resolve([]) : loadRoster(cls.id),
    personal ? Promise.resolve([]) : loadSessions(cls.id, addDays(today, -14)),
    personal ? Promise.resolve([]) : loadPresets(),
    personal ? Promise.resolve([]) : loadSessionsBetween([cls.id], weekStart, weekEnd),
    personal ? Promise.resolve([]) : loadClasses(),
  ]);
  const filed = await loadWorkoutsByIds([...filing.keys()]);
  const filedIds = new Set(filed.map((w) => w.id));

  // Student workouts = anything not generated by the owner (the owner's are samples).
  const studentRuns = personal ? recent : recent.filter((w) => w.created_by !== account.id);
  const byDay = new Map<string, WorkoutRow[]>();
  for (const w of studentRuns) {
    const k = dayKey(w.created_at);
    byDay.set(k, [...(byDay.get(k) ?? []), w]);
  }

  // Sessions (teacher classes): the week grid, then what's planned after it and
  // the last two weeks, each outside the week shown.
  const todaySession = sessions.find((x) => x.session_date === today) ?? null;
  const inWeek = (d: string) => d >= weekStart && d <= weekEnd;
  const upcoming = sessions.filter((x) => x.session_date > today && !inWeek(x.session_date));
  const past = sessions.filter((x) => x.session_date < today && !inWeek(x.session_date)).reverse();
  const weekDays = [0, 1, 2, 3, 4].map((i) => {
    const date = addDays(weekStart, i);
    const s = weekSessions.find((x) => x.session_date === date);
    return { date, session: s ? { name: s.name ?? "", summary: `${s.config.duration} min · ${s.config.intensity} · ${s.config.focus}` } : null };
  });
  const otherClasses = myClasses
    .filter((c) => c.owner_id === account.id && c.kind === "class" && !c.archived && c.code !== code)
    .map((c) => ({ code: c.code, label: classLabel(c) }));
  const sessionNames = new Map(sessions.map((x) => [x.id, x.name || "Untitled session"]));
  const taken = new Set(sessions.map((x) => x.session_date));
  let planDate = today; // the next school day (Mon–Fri) without a session
  while (taken.has(planDate) || weekdayOf(planDate) === 0 || weekdayOf(planDate) === 6) planDate = addDays(planDate, 1);
  const copyOptions = [...sessions].reverse().map((x) => ({
    value: x.session_date,
    label: `${dayLabel(x.session_date)} · ${x.name || "Untitled session"}`,
  }));

  const perStudent = new Map<string, { today: number; total: number; last: string | null }>();
  for (const w of studentRuns) {
    if (!w.created_by) continue;
    const st = perStudent.get(w.created_by) ?? { today: 0, total: 0, last: null };
    st.total += 1;
    if (dayKey(w.created_at) === today) st.today += 1;
    if (!st.last) st.last = w.created_at;
    perStudent.set(w.created_by, st);
  }

  const h = await headers();
  const origin = `${h.get("x-forwarded-proto") ?? "https"}://${h.get("host")}`;
  const studentLink = `${origin}/c/${code}`;

  const heading = "t-section mb-1";

  const archivedNote = cls.archived && (
    <Card style={{ borderColor: "var(--accent2)" }}>
      <div className="text-[14px] leading-[1.5]">
        This class is archived. It&apos;s hidden from your list{personal ? "" : ", and students can still use the code"}.
      </div>
    </Card>
  );

  const filedSection = (
    <section>
      <h2 className={heading}>Filed workouts</h2>
      <div className="text-muted text-[14px] mb-4">Workouts you pinned to {classLabel(cls)}.</div>
      {filed.length === 0 ? (
        <div className="text-muted text-[14px]">Nothing filed yet. Use &ldquo;+ File&rdquo; on any workout.</div>
      ) : (
        <div className="flex flex-col gap-2">
          {filed.map((w) => <WorkoutLine key={w.id} w={w} code={code} ownerId={account.id} filed showDay />)}
        </div>
      )}
    </section>
  );

  const workoutsSection = (
    <section>
      <h2 className={heading}>{personal ? "Your workouts" : "Student workouts"}</h2>
      <div className="text-muted text-[14px] mb-4">
        {personal ? "Everything you generated here in the last 90 days." : "Everything generated with this code in the last 14 days."}
      </div>
      {byDay.size === 0 ? (
        <div className="text-muted text-[14px]">{personal ? "No workouts yet. Tap Start a workout." : "No student workouts yet. Share the code to get started."}</div>
      ) : (
        [...byDay.entries()].map(([day, list]) => {
          const sessionName = list.map((w) => w.session_id && sessionNames.get(w.session_id)).find(Boolean);
          return (
            <div key={day} className="mb-5">
              <div className="text-[12px] font-semibold text-muted uppercase tracking-[0.8px] mb-2">
                {dayLabel(day)}{sessionName ? ` · ${sessionName}` : ""} · {list.length} workout{list.length === 1 ? "" : "s"}
              </div>
              <div className="flex flex-col gap-2">
                {list.map((w) => <WorkoutLine key={w.id} w={w} code={code} ownerId={account.id} filed={filedIds.has(w.id)} />)}
              </div>
            </div>
          );
        })
      )}
    </section>
  );

  const footer = (
    <div className="mt-10 flex justify-between items-center gap-3">
      <Link href={home} className="text-muted text-[13px] inline-flex items-center gap-1"><ArrowLeft className="icon" />{personal ? "Home" : "All classes"}</Link>
      <ArchiveToggle code={code} archived={cls.archived} home={home} />
    </div>
  );

  // A student's personal class: one column, as before.
  if (personal) return (
    <Layout backHref={home} backLabel="Home">
      <div className="mb-4"><LabelEditor code={code} label={cls.label ?? ""} /></div>
      <Link
        href={`/c/${code}`}
        className="flex items-center justify-center gap-2 w-full bg-accent text-bg rounded-lg px-7 py-4 font-display text-[22px] font-bold uppercase tracking-[0.5px] no-underline mb-6"
      >
        <Zap className="icon" /> Start a workout
      </Link>
      {archivedNote}
      <ClassEditor code={code} initialConfig={cls.config} kind={cls.kind} />
      <div className="mt-10">{filedSection}</div>
      <div className="mt-10">{workoutsSection}</div>
      {footer}
    </Layout>
  );

  const sessionsTab = (
    <div className="lg:grid lg:grid-cols-[320px_minmax(0,1fr)] lg:gap-6 lg:items-start">
      <div>
        <div className="bg-surface2 border-[1.5px] border-accent rounded-xl p-6 text-center mb-4">
          <div className="t-eyebrow text-muted mb-2">Class code for students</div>
          <div className="font-display text-[52px] font-black text-accent tracking-[8px] leading-none mb-3.5">{code}</div>
          <div className="flex justify-center gap-2 flex-wrap">
            <CopyButton text={code} label="Copy code" />
            <CopyButton text={studentLink} label="Copy student link" />
            <Link
              href={`/classes/${code}/projector`}
              className="inline-flex items-center gap-1.5 bg-[rgba(200,255,0,0.1)] border border-[rgba(200,255,0,0.3)] text-accent px-4 py-2 rounded-md text-[13px] font-semibold no-underline"
            >
              <Monitor className="icon" /> Projector
            </Link>
          </div>
          <div className="text-muted text-[12px] mt-3">Students sign in with their Mitty account, then enter the code.</div>
        </div>
        {archivedNote}
      </div>
      <section>
        <h2 className={heading}>Sessions</h2>
        <div className="text-muted text-[14px] mb-4">
          Each day can have its own settings. On a day without a session, students get the default settings.
        </div>
        <WeekPlanner code={code} today={today} weekStart={weekStart} thisWeek={thisWeek} days={weekDays} otherClasses={otherClasses} />
        {upcoming.length > 0 && (
          <>
            <div className="t-label mb-2">Coming up</div>
            <div className="flex flex-col gap-2">
              {upcoming.map((x) => <SessionLine key={x.id} s={x} code={code} />)}
            </div>
          </>
        )}
        <Card className="mt-4">
          <CardTitle>Plan any day</CardTitle>
          <PlanSessionForm code={code} defaultDate={planDate} minDate={today} copyOptions={copyOptions} presets={presets} />
        </Card>
        {past.length > 0 && (
          <details>
            <summary className="text-muted text-[13px] cursor-pointer">Past sessions ({past.length})</summary>
            <div className="flex flex-col gap-2 mt-2">
              {past.map((x) => <SessionLine key={x.id} s={x} code={code} />)}
            </div>
          </details>
        )}
      </section>
    </div>
  );

  const studentsTab = (
    <div className="lg:grid lg:grid-cols-2 lg:gap-6 lg:items-start">
      <section className="mb-10 lg:mb-0">
        <h2 className={heading}>Roster</h2>
        <div className="text-muted text-[14px] mb-4">Students who joined with the code, and their workouts in the last 14 days.</div>
        {roster.length === 0 ? (
          <div className="text-muted text-[14px]">No one has joined yet.</div>
        ) : (
          <Card className="!p-0 overflow-hidden">
            {roster.map((r, i) => {
              const st = perStudent.get(r.user_id);
              return (
                <div key={r.user_id} className={`flex items-center justify-between gap-3 px-5 py-3 ${i ? "border-t border-border" : ""}`}>
                  <div className="min-w-0">
                    <div className="font-semibold text-[15px] truncate">{r.name}</div>
                    <div className="text-[12px] text-muted truncate">{r.email}</div>
                  </div>
                  <div className="text-right shrink-0">
                    <div className="font-display text-[20px] font-bold text-accent2 leading-none">{st?.total ?? 0}</div>
                    <div className="text-[11px] text-muted mt-0.5">
                      {st?.today ? `${st.today} today` : st?.last ? dayLabel(dayKey(st.last)) : "no workouts"}
                    </div>
                  </div>
                </div>
              );
            })}
          </Card>
        )}
      </section>
      <div className="flex flex-col gap-10">
        <section>
          <h2 className={heading}>Ratings</h2>
          <div className="text-muted text-[14px] mb-4">What students said in the last 14 days.</div>
          {reviews.length === 0 ? (
            <div className="text-muted text-[14px]">No ratings yet.</div>
          ) : (
            <Card>
              <CardTitle>
                {reviews.length} rating{reviews.length === 1 ? "" : "s"} · average{" "}
                {(reviews.reduce((s, r) => s + r.rating, 0) / reviews.length).toFixed(1)} stars
              </CardTitle>
              <div className="flex flex-col">
                {reviews.map((r, i) => (
                  <div key={i} className="border-t border-border py-3 first:border-t-0 first:pt-0">
                    <div className="flex justify-between gap-3 text-[13px]">
                      <Stars rating={r.rating} />
                      <span className="text-muted">{r.student_name || "Student"} · {dayLabel(dayKey(r.created_at))} {timeLabel(r.created_at)}</span>
                    </div>
                    {r.comment && <div className="text-[14px] leading-[1.5] mt-1">{r.comment}</div>}
                  </div>
                ))}
              </div>
            </Card>
          )}
        </section>
      </div>
    </div>
  );

  const workoutsTab = (
    <div className="lg:grid lg:grid-cols-2 lg:gap-6 lg:items-start">
      <div className="mb-10 lg:mb-0">{workoutsSection}</div>
      {filedSection}
    </div>
  );

  return (
    <Layout backHref={home} backLabel="Classes" wide>
      <div className="mb-6 md:max-w-[620px]"><LabelEditor code={code} label={cls.label ?? ""} /></div>
      {(
        <TodayPanel
          code={code}
          dateLabel={longDayLabel(today)}
          session={todaySession && { date: todaySession.session_date, name: todaySession.name ?? "" }}
          settings={{ ...DEFAULT_CONFIG, ...(todaySession?.config ?? cls.config) }}
          students={roster.map((r) => ({ userId: r.user_id, name: r.name, today: perStudent.get(r.user_id)?.today ?? 0 }))}
          ratings={reviews.filter((r) => dayKey(r.created_at) === today).map((r) => r.rating)}
        />
      )}
      <Tabs
        initial={tab}
        tabs={[
          { id: "sessions", label: "Sessions", content: sessionsTab },
          { id: "settings", label: "Settings", content: <ClassEditor code={code} initialConfig={cls.config} kind={cls.kind} classConfig={cls.config} presets={presets} /> },
          { id: "ai", label: "AI background", content: <AIBackgroundCard code={code} config={cls.config} /> },
          { id: "students", label: "Students", content: studentsTab },
          { id: "workouts", label: "Workouts", content: workoutsTab },
        ]}
      />
      {footer}
    </Layout>
  );
}

function WorkoutLine({ w, code, ownerId, filed, showDay = false }: {
  w: WorkoutRow; code: string; ownerId: string; filed: boolean; showDay?: boolean;
}) {
  const who = w.created_by === ownerId ? (w.student_name ? "You" : "Your sample") : w.student_name || "Student";
  return (
    <div className="flex items-center justify-between gap-3 bg-surface border border-border rounded-xl px-4 py-3">
      <div className="min-w-0">
        <Link href={`/w/${w.id}`} className="font-semibold text-[15px] text-text no-underline hover:text-accent block truncate">
          {w.title || "Workout"}
        </Link>
        <div className="text-[12px] text-muted">
          {who} · {showDay ? `${dayLabel(dayKey(w.created_at))} ` : ""}{timeLabel(w.created_at)}
        </div>
      </div>
      <FileToggle code={code} workoutId={w.id} filed={filed} />
    </div>
  );
}

function SessionLine({ s, code }: { s: ClassSession; code: string }) {
  return (
    <Link
      href={`/classes/${code}/s/${s.session_date}`}
      className="flex items-center justify-between gap-3 bg-surface border border-border rounded-xl px-4 py-3 no-underline text-text hover:border-accent"
    >
      <div className="min-w-0">
        <div className="t-eyebrow text-muted">{dayLabel(s.session_date)}</div>
        <div className="font-semibold text-[15px] truncate">{s.name || "Untitled session"}</div>
      </div>
      <div className="text-[12px] text-muted text-right shrink-0">
        {s.config.duration} min · {s.config.intensity} · {s.config.focus}
      </div>
    </Link>
  );
}

/** A rating as five line stars, the first `rating` filled. */
function Stars({ rating }: { rating: number }) {
  return (
    <span className="inline-flex gap-0.5 text-accent" aria-label={`${rating} of 5 stars`}>
      {[1, 2, 3, 4, 5].map((n) => (
        <Star key={n} className={n <= rating ? "w-3.5 h-3.5 fill-current" : "w-3.5 h-3.5 text-border"} aria-hidden />
      ))}
    </span>
  );
}
